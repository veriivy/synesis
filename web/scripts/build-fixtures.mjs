// Regenerates lib/fixtures/stream.ts from /fixtures/stream.jsonl.
// Run with: npm run fixtures
// /fixtures is the frozen contract and is read-only from here.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../fixtures/stream.jsonl");
const out = resolve(here, "../lib/fixtures/stream.ts");

const events = readFileSync(src, "utf8")
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean)
  .map((l, i) => {
    try {
      return JSON.parse(l);
    } catch (e) {
      throw new Error(`stream.jsonl line ${i + 1} is not valid JSON: ${e.message}`);
    }
  });

const banner = `// GENERATED by scripts/build-fixtures.mjs from /fixtures/stream.jsonl. Do not edit.
// ${events.length} events, happy path, in order.

import type { SSEEvent } from "../contract";

export const fixtureStream: SSEEvent[] = `;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${banner}${JSON.stringify(events, null, 2)};\n`, "utf8");
console.log(`wrote ${out} (${events.length} events)`);
